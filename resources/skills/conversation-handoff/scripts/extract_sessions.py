"""Digest Claude Code session transcripts (JSONL) into local handoff markdown.

Usage:
    python extract_sessions.py --projects-dir <claude-projects-dir>/<project-slug> --out-dir <dir>

The projects dir is Claude Code's per-project transcript folder, under the
user's ~/.claude/projects/. Set it explicitly; there is no default.

Streams each top-level *.jsonl transcript. For every real user request it
records the timestamp, the request text (truncated), and the last assistant
text block that followed it (the turn's outcome). Writes one markdown file
per session plus an index README.md. Subagent folders and tool results are
not read.
"""

import argparse
import json
import re
from pathlib import Path

USER_CAP = 700      # chars kept per user request
REPLY_CAP = 900     # chars kept per assistant outcome
SYSTEM_PREFIX = re.compile(r"^\s*<(browser_instruction|system-reminder|command-name|local-command)")


def text_of(content):
    """Return the plain text parts of a message content field."""
    if isinstance(content, str):
        return [content]
    parts = []
    if isinstance(content, list):
        for block in content:
            if isinstance(block, dict) and block.get("type") == "text":
                parts.append(block.get("text", ""))
    return parts


def clip(text, cap):
    text = " ".join(text.split())
    return text if len(text) <= cap else text[:cap].rstrip() + " ..."


def digest(path):
    turns = []          # list of dicts: ts, request, outcome
    first_ts = last_ts = None
    session_id = path.stem
    assistant_text_count = 0
    with path.open(encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            ts = rec.get("timestamp")
            if ts:
                first_ts = first_ts or ts
                last_ts = ts
            kind = rec.get("type")
            msg = rec.get("message") or {}
            if rec.get("isSidechain"):
                continue
            if kind == "user":
                content = msg.get("content")
                # Skip tool-result-only user records (not human requests).
                if isinstance(content, list) and content and all(
                    isinstance(b, dict) and b.get("type") == "tool_result" for b in content
                ):
                    continue
                texts = [t for t in text_of(content) if t.strip() and not SYSTEM_PREFIX.match(t)]
                if not texts:
                    continue
                turns.append({"ts": ts, "request": clip(" ".join(texts), USER_CAP), "outcome": ""})
            elif kind == "assistant":
                texts = [t for t in text_of(msg.get("content")) if t.strip()]
                if texts and turns:
                    assistant_text_count += 1
                    turns[-1]["outcome"] = clip(texts[-1], REPLY_CAP)
    return {
        "session_id": session_id,
        "first_ts": first_ts or "unknown",
        "last_ts": last_ts or "unknown",
        "turns": turns,
        "assistant_text_blocks": assistant_text_count,
        "size_mb": round(path.stat().st_size / 1e6, 1),
    }


def write_session(info, out_dir):
    name = f"session_{info['session_id'][:8]}.md"
    lines = [
        f"# Session {info['session_id']}",
        "",
        f"- First event: {info['first_ts']}",
        f"- Last event: {info['last_ts']}",
        f"- Human requests recorded: {len(info['turns'])}",
        f"- Transcript size: {info['size_mb']} MB",
        "- Source: local Claude Code transcript; not committed, not published.",
        "",
        "## Requests and outcomes",
        "",
    ]
    for i, t in enumerate(info["turns"], 1):
        lines.append(f"### {i}. {t['ts'] or ''}")
        lines.append(f"**Request:** {t['request']}")
        lines.append("")
        if t["outcome"]:
            lines.append(f"**Outcome:** {t['outcome']}")
            lines.append("")
    (out_dir / name).write_text("\n".join(lines), encoding="utf-8")
    return name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--projects-dir", required=True)
    ap.add_argument("--out-dir", required=True)
    args = ap.parse_args()

    src = Path(args.projects_dir)
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    index = ["# Conversation handoff index", "",
             "Local digests of every top-level Claude Code session in this repo.",
             "Generated by `.claude/skills/conversation-handoff/scripts/extract_sessions.py`.",
             "", "| Session | First event | Last event | Requests | File |",
             "|---|---|---|---|---|"]
    for jsonl in sorted(src.glob("*.jsonl"), key=lambda p: p.stat().st_mtime):
        info = digest(jsonl)
        fname = write_session(info, out)
        index.append(f"| `{info['session_id']}` | {info['first_ts']} | {info['last_ts']} | "
                     f"{len(info['turns'])} | [{fname}]({fname}) |")
        print(f"{info['session_id']}: {len(info['turns'])} requests -> {fname}")
    (out / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
